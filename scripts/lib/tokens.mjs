// Turns design/palette.json into CSS colour tokens for light and dark, and checks contrast.
import { contrast, ensureContrast, hexToOklch, mix, oklchToHex, readableOn } from "./color.mjs";

const KEYS = ["bg", "surface", "surface-2", "ink", "ink-soft", "line", "primary", "primary-ink", "accent", "gold", "success", "warning", "error", "info"];

function deriveDark(light) {
  const hue = hexToOklch(light.primary).h;
  const tint = (L, C) => oklchToHex({ L, C, h: hue });
  const bg = tint(0.175, 0.016);
  const surface = tint(0.215, 0.02);
  const surface2 = tint(0.26, 0.024);
  const line = tint(0.335, 0.024);
  const lift = (hex, floor) => {
    const o = hexToOklch(hex);
    o.L = Math.max(o.L, floor);
    const lifted = oklchToHex(o);
    return ensureContrast(lifted, [bg, surface, surface2, mix(lifted, surface, 12)], 4.7, "lighter");
  };
  const primary = lift(light.primary, 0.74);
  return {
    bg, surface, "surface-2": surface2, line,
    ink: tint(0.95, 0.008),
    "ink-soft": tint(0.78, 0.018),
    primary, "primary-ink": readableOn(primary),
    accent: lift(light.accent, 0.74), gold: lift(light.gold, 0.78),
    success: lift(light.success, 0.74), warning: lift(light.warning, 0.78),
    error: lift(light.error, 0.74), info: lift(light.info, 0.74),
  };
}

function check(label, t) {
  const soft = mix(t.primary, t.surface, 8);
  const pairs = [];
  for (const fg of ["ink", "ink-soft", "primary", "accent", "gold", "success", "warning", "error", "info"]) {
    for (const bg of ["bg", "surface", "surface-2"]) pairs.push([fg, bg]);
  }
  const out = pairs.filter(([fg, bg]) => contrast(t[fg], t[bg]) < 4.5).map(([fg, bg]) => ({ label, pair: `${fg} on ${bg}`, ratio: contrast(t[fg], t[bg]) }));
  if (contrast(t["primary-ink"], t.primary) < 4.5) out.push({ label, pair: "primary-ink on primary", ratio: contrast(t["primary-ink"], t.primary) });
  if (contrast(t.ink, soft) < 4.5) out.push({ label, pair: "ink on primary tint", ratio: contrast(t.ink, soft) });
  return out;
}

const decl = (t) => KEYS.map((k) => `  --${k}: ${t[k]};`).join("\n");

export function buildTokens(palette) {
  const light = palette.light;
  const dark = { ...deriveDark(light), ...(palette.dark || {}) };
  const failures = [...check("light", light), ...check("dark", dark)];
  const css = `/* Generated by scripts/build.mjs from design/palette.json. Edit the JSON, not this file. */
:root {
${decl(light)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decl(dark).replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
${decl(dark)}
}
`;
  return { css, failures, light, dark };
}
